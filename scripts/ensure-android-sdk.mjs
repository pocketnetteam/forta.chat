/**
 * Ensures android/local.properties exists with a valid sdk.dir (machine-local, gitignored).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localPropsPath = path.join(root, 'android', 'local.properties');

function escapeSdkDir(dir) {
  return dir.replace(/\\/g, '\\\\');
}

function defaultSdkCandidates() {
  const home = os.homedir();
  switch (process.platform) {
    case 'win32':
      return [
        process.env.ANDROID_HOME,
        process.env.ANDROID_SDK_ROOT,
        path.join(process.env.LOCALAPPDATA ?? '', 'Android', 'Sdk'),
      ];
    case 'darwin':
      return [
        process.env.ANDROID_HOME,
        process.env.ANDROID_SDK_ROOT,
        path.join(home, 'Library', 'Android', 'sdk'),
      ];
    default:
      return [
        process.env.ANDROID_HOME,
        process.env.ANDROID_SDK_ROOT,
        path.join(home, 'Android', 'Sdk'),
      ];
  }
}

function findSdkDir() {
  for (const candidate of defaultSdkCandidates()) {
    if (!candidate) continue;
    const sdkDir = path.resolve(candidate);
    if (fs.existsSync(path.join(sdkDir, 'platform-tools'))) {
      return sdkDir;
    }
  }
  return null;
}

function readExistingSdkDir(contents) {
  const match = contents.match(/^sdk\.dir=(.+)$/m);
  if (!match) return null;
  return match[1].replace(/\\\\/g, '\\');
}

let contents = '';
if (fs.existsSync(localPropsPath)) {
  contents = fs.readFileSync(localPropsPath, 'utf8');
  const existing = readExistingSdkDir(contents);
  if (existing && fs.existsSync(path.join(existing, 'platform-tools'))) {
    process.exit(0);
  }
}

const sdkDir = findSdkDir();
if (!sdkDir) {
  console.error(
    '[cap] Android SDK not found. Install Android Studio or set ANDROID_HOME, then create android/local.properties with sdk.dir.',
  );
  process.exit(1);
}

const line = `sdk.dir=${escapeSdkDir(sdkDir)}`;
const next = contents.includes('sdk.dir=')
  ? contents.replace(/^sdk\.dir=.*$/m, line)
  : `${contents.trimEnd()}\n${line}\n`;

fs.writeFileSync(localPropsPath, next.startsWith('#') || next.startsWith('sdk.') ? next : `# Auto-generated by scripts/ensure-android-sdk.mjs\n${next}`);
console.log(`[cap] android/local.properties → sdk.dir=${sdkDir}`);
